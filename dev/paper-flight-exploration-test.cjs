const assert=require('node:assert/strict');
const E=require('../assets/paper-flight/exploration.js');
const P=require('../assets/paper-flight/physics.js');
assert.deepEqual(E.landmarks.map(({id,name,east,north,radius,kind})=>({id,name,east,north,radius,kind})),P.LANDMARKS,'exploration and terrain share the same landmarks');
const plane=(extra={})=>({east:0,north:0,y:70,pitch:0,heading:90,landed:false,...extra});
let run=E.create(),p=plane();
assert.equal(E.navigation(run,p).bearing,90);
assert.equal(E.navigation(run,p).relativeBearing,0);
E.cycleWaypoint(run);
assert.ok(E.navigation(run,p).relativeBearing<0,'ridge lies left of initial east heading');
E.cycleWaypoint(run,-1);
assert.equal(E.navigation(run,p).name,'Sunfield');
E.cycleWaypoint(run,-1);
assert.equal(E.navigation(run,p).name,'Storm Arch');
run=E.create();p=plane({east:220});
E.step(run,p,{},1/60);
assert.equal(run.bonus,25);
assert.equal(p.explorationBonus,25);
assert.equal(run.discoveries.length,1);
for(let i=0;i<60;i++)E.step(run,p,{},1/60);
assert.equal(run.bonus,25,'landmark pays once');
run=E.create();p=plane();
E.step(run,p,{fire:true},1/60);
assert.equal(run.tags,1,'initial kite is reachable by aiming ahead');
assert.equal(run.pulses[0].hit,true);
assert.equal(run.bursts.length,1);
assert.equal(p.explorationBonus,10);
E.step(run,p,{fire:true},1/60);
assert.equal(run.pulses.length,1,'cooldown suppresses a second pulse');
for(let i=0;i<100;i++)E.step(run,p,{},1/60);
assert.equal(run.pulses.length,0);
assert.equal(run.bursts.length,0);
E.step(run,p,{fire:true},1/60);
assert.equal(run.tags,1,'inactive kite cannot be farmed');
run=E.create();p=plane({heading:270});
E.step(run,p,{fire:true},1/60);
assert.equal(run.tags,0,'targets behind cannot be hit');
assert.equal(run.pulses[0].hit,false);
run=E.create();p=plane({y:250});
E.step(run,p,{fire:true},1/60);
assert.equal(run.tags,0,'altitude affects aiming');
run=E.create();p=plane({east:-500});
E.step(run,p,{fire:true},1/60);
assert.equal(run.tags,0,'range is limited');
run=E.create();p=plane({landed:true,east:220});
E.step(run,p,{fire:true},1/60);
assert.equal(run.time,0);
assert.equal(run.bonus,0);
assert.equal(E.relative(plane({heading:359}),{east:1,north:100,y:70}).relativeBearing<2,true,'bearing wraps through north');
const a=E.create(),b=E.create();
assert.deepEqual(a,b,'world deterministic across launches');
a.landmarks[0].name='changed';
assert.equal(b.landmarks[0].name,'Sunfield','run state independent');
console.log('Paper Flight exploration: bearings, discoveries, aiming, cooldowns, rewards and cleanup passed.');

// Ribbon collision sweeps the travelled segment, so fast flights cannot skip a pickup.
run=E.create();p=plane({east:80,energy:.3});E.step(run,p,{},1/60);p.east=140;E.step(run,p,{},1/60);
assert.equal(run.ringsCollected,1);assert.equal(p.ribbons,1);assert.equal(run.bonus,5);assert.equal(p.energy,.52);
p.east=80;E.step(run,p,{},1/60);assert.equal(run.bonus,5,'collected ribbons cannot be farmed');
run=E.create();p=plane({east:80,y:110,energy:.9});E.step(run,p,{},1/60);p.east=140;E.step(run,p,{},1/60);assert.equal(run.ringsCollected,0,'must fly through the ribbon altitude');
p=plane({east:110,energy:.95});run=E.create();E.step(run,p,{},1/60);assert.equal(p.energy,1,'recharge capped at full');
console.log('Breeze ribbons: swept collisions, altitude, single rewards and energy cap passed.');
